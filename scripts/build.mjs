import {readFile,mkdir,writeFile,cp,rm} from 'node:fs/promises';
let html=await readFile('app/index.html','utf8');
const vocabularyUI=await readFile('app/vocabulary-ui.js','utf8');
html=html.replace('/* VOCABULARY_UI */',()=>vocabularyUI);
const deadlineUI=await readFile('app/deadline-ui.js','utf8');
const deadlineUtils=(await readFile('app/deadlines.js','utf8')).replaceAll('export function','function');
html=html.replace('/* DEADLINE_UTILS */',()=>deadlineUtils);
html=html.replace('/* DEADLINE_UI */',()=>deadlineUI);
const auth=await readFile('worker/auth.js','utf8');
const api=(await readFile('worker/api.js','utf8')).replace(/^import .*;\n/gm,'');
const vocab=(await readFile('worker/vocabulary.js','utf8')).replace(/^import .*;\n/gm,'');
const guide=await readFile('사용방법.txt','utf8');
await rm('dist',{recursive:true,force:true});
await mkdir('dist/server',{recursive:true});
await mkdir('dist/.openai',{recursive:true});
const entry=auth+vocab+api+`\nconst page=${JSON.stringify(html)};\nconst guide=${JSON.stringify(guide)};\nexport default { async fetch(request,env) { const p=new URL(request.url).pathname;if(p.startsWith('/api/'))return handleAPI(request,env);if(p==='/guide.txt')return new Response(guide,{headers:{'content-type':'text/plain; charset=utf-8','content-disposition':"attachment; filename=homework-guide.txt"}});if(p!=='/')return new Response('Not found',{status:404});return new Response(page,{headers:{'content-type':'text/html; charset=utf-8','cache-control':'no-store','x-content-type-options':'nosniff','referrer-policy':'same-origin'}});}};\n`;
await writeFile('dist/server/index.js',entry);
await cp('.openai/hosting.json','dist/.openai/hosting.json');
await cp('drizzle','dist/drizzle',{recursive:true});
const mod=await import('data:text/javascript;base64,'+Buffer.from(entry).toString('base64'));
if(typeof mod.default.fetch!=='function')throw new Error('Worker fetch missing');
const res=await mod.default.fetch(new Request('https://example.test/'),{});
if(res.status!==200||!(await res.text()).includes('병준이의 숙제 노트'))throw new Error('HTML response invalid');
if(html.includes('/* VOCABULARY_UI */')||!html.includes("$$('.quiz-answer')"))throw new Error('Vocabulary UI embedding failed');
if(/Tesseract|tesseract\.js|recognizePhoto|ocr-raw/.test(html))throw new Error('Automatic photo recognition must not be bundled');
const script=html.match(/<script>([\s\S]*)<\/script>/)[1];
new Function(script);
console.log('Built Worker, checked HTML response and browser script syntax.');
